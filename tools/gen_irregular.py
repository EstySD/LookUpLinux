"""Generate lookup/data/irregular.txt and NOTICE-wordnet.txt from WordNet 3.1.

Usage: python -I tools/gen_irregular.py <wordnet dict folder> <output folder>

Reads verb.exc, noun.exc, adj.exc (lines "inflected base [base ...]") and, for
the licence notice, the first 29 lines of data.noun. The input is plain text,
read as data only: nothing from the input folder is imported or executed.
"""
import re
import sys
from pathlib import Path

SOURCES = ("verb.exc", "noun.exc", "adj.exc")
LICENSE_SOURCE = "data.noun"
LICENSE_LINES = 29
TOKEN_RE = re.compile(r"[a-z][a-z'-]*\Z")
NUMBER_PREFIX_RE = re.compile(r"^\s*\d+ ?")

HEADER = """\
# Irregular English word forms mapped to their base forms.
# Derived from the WordNet 3.1 exception lists verb.exc, noun.exc and adj.exc
# (WordNet 3.1 Copyright 2011 by Princeton University; see NOTICE-wordnet.txt).
# Generated by tools/gen_irregular.py - do not edit by hand.
# Format: whitespace separated; the first field is the inflected form, the
# remaining fields are candidate base forms (most likely first). Lines starting
# with # are comments. Sorted by form, one line per form.
"""

NOTICE_LEAD = """\
lookup/data/irregular.txt is derived from the exception lists (verb.exc,
noun.exc, adj.exc) of WordNet 3.1. WordNet is distributed under the following
licence; the notice is reproduced as the licence requires.

"""


def parse_exceptions(path: Path):
    """Yield (form, [bases]) for the valid lines of one .exc file."""
    text = path.read_bytes().decode("utf-8", errors="replace")
    for line in text.splitlines():
        fields = line.split()
        if len(fields) < 2:
            continue
        if not all(TOKEN_RE.match(tok) for tok in fields):
            continue  # capitals, underscores (collocations), digits, odd marks
        yield fields[0], fields[1:]


def build_table(dict_dir: Path) -> dict:
    table: dict = {}
    for name in SOURCES:
        path = dict_dir / name
        if not path.is_file():
            continue
        for form, bases in parse_exceptions(path):
            seen = table.setdefault(form, [])
            for base in bases:
                if base not in seen:
                    seen.append(base)
    return table


def render_table(table: dict) -> str:
    lines = [form + " " + " ".join(table[form]) for form in sorted(table)]
    return HEADER + "\n".join(lines) + "\n"


def read_license(path: Path):
    """Return the licence text from the first lines of data.noun, or None."""
    out = []
    with open(path, "rb") as fh:
        for _ in range(LICENSE_LINES):
            raw = fh.readline()
            if not raw:
                break
            line = raw.decode("utf-8", errors="replace").rstrip("\r\n")
            out.append(NUMBER_PREFIX_RE.sub("", line).rstrip())
    text = "\n".join(out).strip()
    if not text.startswith("This software and database is being provided to you"):
        return None
    return text


def main(argv) -> int:
    if len(argv) != 3:
        print("usage: gen_irregular.py <wordnet dict folder> <output folder>", file=sys.stderr)
        return 2
    dict_dir, out_dir = Path(argv[1]), Path(argv[2])
    table = build_table(dict_dir)
    if not table:
        print("no usable exception entries found", file=sys.stderr)
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "irregular.txt", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_table(table))
    print("irregular.txt: %d forms" % len(table))
    source = dict_dir / LICENSE_SOURCE
    if source.is_file():
        notice = read_license(source)
        if notice is None:
            print("licence text not found at the top of %s" % LICENSE_SOURCE, file=sys.stderr)
            return 1
        with open(out_dir / "NOTICE-wordnet.txt", "w", encoding="utf-8", newline="\n") as fh:
            fh.write(NOTICE_LEAD + notice + "\n")
        print("NOTICE-wordnet.txt written")
    else:
        print("no %s: notice not written" % LICENSE_SOURCE, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
